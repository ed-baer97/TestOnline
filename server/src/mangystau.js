const GROUP_FLAGS = {
  school: [1, 1, 1, 0],
  primary: [1, 0, 0, 0],
  evening: [0, 1, 1, 0],
}

export function isMangystau(name, nameKk = '') {
  const folded = `${name} ${nameKk}`
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replaceAll('ғ', 'г')
    .replaceAll('ң', 'н')
    .replaceAll('ұ', 'у')
    .replaceAll('ү', 'у')
    .replaceAll('қ', 'к')
    .replaceAll('ө', 'о')
    .replaceAll('і', 'и')
    .replaceAll('ы', 'и')
  return folded.includes('мангистау')
}

export async function ensureMangystauCatalog() {
  await db.tx(async (tx) => {
    const done = await tx.get('SELECT key FROM app_seeds WHERE key = ?', SEED_KEY)
    if (done) return
    const regions = await tx.all('SELECT id, name, name_kk FROM regions')
    let region = regions.find((row) => isMangystau(row.name, row.name_kk || ''))
    const now = new Date().toISOString()
    if (!region) {
      const id = crypto.randomUUID()
      await tx.run(
        'INSERT INTO regions (id, name, name_kk, created_at) VALUES (?, ?, ?, ?)',
        id,
        MANGYSTAU_REGION.name,
        MANGYSTAU_REGION.nameKk,
        now,
      )
      region = { id, name: MANGYSTAU_REGION.name, name_kk: MANGYSTAU_REGION.nameKk }
    } else if (!region.name_kk) {
      await tx.run('UPDATE regions SET name_kk = ? WHERE id = ?', MANGYSTAU_REGION.nameKk, region.id)
    }
    const districtIds = new Map()
    for (const district of MANGYSTAU_DISTRICTS) {
      let row = await tx.get(
        'SELECT id, name_kk FROM districts WHERE region_id = ? AND lower(name) = lower(?)',
        region.id,
        district.name,
      )
      if (!row) {
        const id = crypto.randomUUID()
        await tx.run(
          'INSERT INTO districts (id, region_id, name, name_kk, sort_order, created_at) VALUES (?, ?, ?, ?, ?, ?)',
          id,
          region.id,
          district.name,
          district.nameKk,
          district.order,
          now,
        )
        row = { id, name_kk: district.nameKk }
      } else if (!row.name_kk) {
        await tx.run('UPDATE districts SET name_kk = ? WHERE id = ?', district.nameKk, row.id)
      }
      districtIds.set(district.name, row.id)
    }
    for (const district of MANGYSTAU_DISTRICTS) {
      const districtId = districtIds.get(district.name)
      for (const school of district.schools) {
        const existing = await tx.get(
          'SELECT id FROM organizations WHERE region_id = ? AND lower(name) = lower(?)',
          region.id,
          school.name,
        )
        if (existing) continue
        const flags = GROUP_FLAGS[school.kind] || GROUP_FLAGS.school
        await tx.run(
          `INSERT INTO organizations (id, region_id, district_id, name, name_kk, grades_1_4, grades_5_9, grades_10_11, students, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          crypto.randomUUID(),
          region.id,
          districtId,
          school.name,
          school.nameKk,
          ...flags,
          now,
        )
      }
    }
    await tx.run('INSERT INTO app_seeds (key, applied_at) VALUES (?, ?)', SEED_KEY, now)
  })
}
