let currentLang = readLang()
const listeners = new Set()

function readLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'kk' || saved === 'ru') return saved
  } catch {
    // localStorage can be unavailable
  }
  return 'ru'
}

export function getLang() {
  return currentLang
}

export function pick(lang, ru, kk) {
  const primary = lang === 'kk' ? kk : ru
  const fallback = lang === 'kk' ? ru : kk
  const text = String(primary ?? '').trim()
  return text || String(fallback ?? '').trim()
}

export function translate(lang, input, vars) {
  if (input == null || input === '') return input ?? ''
  const source = String(input)
  const template = lang === 'kk' ? (KK[source] ?? source) : source
  const filled = vars
    ? template.replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? '' : String(vars[key])))
    : template
  if (lang !== 'kk' || Object.prototype.hasOwnProperty.call(KK, source)) return filled
  for (const [pattern, format] of PATTERNS) {
    const match = filled.match(pattern)
    if (match) return format(...match)
  }
  return filled
}

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(currentLang)

  useEffect(() => {
    currentLang = lang
    document.documentElement.lang = lang === 'kk' ? 'kk' : 'ru'
    document.title = lang === 'kk'
      ? 'Saqbol — қаржылық қауіпсіздік'
      : 'Saqbol — финансовая безопасность'
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch {
      // ignore
    }
    for (const listener of listeners) listener(lang)
  }, [lang])

  const value = useMemo(() => ({
    lang,
    setLang,
    t: (input, vars) => translate(lang, input, vars),
  }), [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n outside provider')
  return value
}

export function LanguageToggle() {
  const { lang, setLang, t } = useI18n()
  return (
    <div className="lang-toggle" role="group" aria-label={t('Язык')}>
      <button type="button" className={lang === 'ru' ? 'on' : ''} aria-pressed={lang === 'ru'} onClick={() => setLang('ru')}>Рус</button>
      <button type="button" className={lang === 'kk' ? 'on' : ''} aria-pressed={lang === 'kk'} onClick={() => setLang('kk')}>Қаз</button>
    </div>
  )
}
